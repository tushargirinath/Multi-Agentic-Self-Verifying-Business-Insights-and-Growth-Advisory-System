"""Critic Agent: 5-Layer Self-Verification Pipeline and Confidence Scoring (Section 16)."""
import re
from typing import Dict, Any, List, Optional, Tuple
import duckdb
from app.config import settings


class CriticAgent:
    """
    Independently verifies every answer generated by analytical agents before it reaches the user.
    Uses independent alternative queries, mathematical invariants, grounding checks, and rubric evaluation.
    """

    def __init__(self, duckdb_conn: Optional[duckdb.DuckDBPyConnection] = None, tolerance: float = settings.MAVIS_CRITIC_TOLERANCE):
        if duckdb_conn:
            self.con = duckdb_conn
        else:
            try:
                self.con = duckdb.connect(settings.duckdb_path, read_only=False)
            except Exception:
                self.con = duckdb.connect(settings.duckdb_path, read_only=True)
        self.tolerance = tolerance

    def verify_answer(
        self,
        question: str,
        answer: Dict[str, Any],
        dataset_id: str = "ds_reference",
        dqs_score: float = 95.0
    ) -> Dict[str, Any]:
        """
        Execute 5-layer verification pipeline on the draft answer.
        Layers:
            L1: Recompute headline numbers independently
            L2: Sanity and invariant checks
            L3: Text-to-evidence grounding
            L4: Chart-to-claim consistency check
            L5: Language and causal rubric
        """
        issues: List[Dict[str, Any]] = []

        # Layer 1: Independent Recompute
        l1_pass, l1_score, l1_issues = self._verify_l1_recompute(answer, dataset_id)
        issues.extend(l1_issues)

        # Layer 2: Sanity & Invariants
        l2_pass, l2_score, l2_issues = self._verify_l2_sanity(answer)
        issues.extend(l2_issues)

        # Layer 3: Text Grounding
        l3_pass, l3_score, l3_issues = self._verify_l3_grounding(answer)
        issues.extend(l3_issues)

        # Layer 4: Chart Verification
        l4_pass, l4_score, l4_issues = self._verify_l4_chart(answer)
        issues.extend(l4_issues)

        # Layer 5: Rubric
        l5_pass, l5_score, l5_issues = self._verify_l5_rubric(question, answer)
        issues.extend(l5_issues)

        # Factors
        dq_factor = min(1.0, max(0.0, dqs_score / 100.0))
        sample_size_factor = 1.0  # reference dataset has >500k rows

        # Formula: Section 16.1
        # confidence = 0.35*recompute_match + 0.20*sanity_pass + 0.15*grounding_score
        #              + 0.10*data_quality_factor + 0.10*sample_size_factor + 0.10*rubric_score
        confidence_val = (
            0.35 * l1_score +
            0.20 * l2_score +
            0.15 * l3_score +
            0.10 * dq_factor +
            0.10 * sample_size_factor +
            0.10 * l5_score
        )
        confidence_score = round(confidence_val, 2)

        if confidence_score >= 0.85:
            label = "High"
        elif confidence_score >= 0.65:
            label = "Medium"
        else:
            label = "Low"

        # Decision Matrix (Section 16.2)
        has_critical_recompute_fail = any(i["layer"] == "L1" and i.get("delta_pct", 0) > self.tolerance * 100 for i in issues)
        has_sanity_fail = not l2_pass
        has_grounding_fail = not l3_pass
        has_rubric_fail = not l5_pass

        if not has_critical_recompute_fail and not has_sanity_fail and not has_grounding_fail and not has_rubric_fail and confidence_score >= 0.85:
            verdict = "pass"
        elif not has_critical_recompute_fail and not has_sanity_fail and not has_grounding_fail and not has_rubric_fail:
            verdict = "pass_with_note"
        elif has_critical_recompute_fail or has_grounding_fail or has_rubric_fail:
            verdict = "repair"
        else:
            verdict = "block"

        return {
            "verdict": verdict,
            "confidence": {"label": label, "score": confidence_score},
            "layers": {
                "L1_recompute": "pass" if l1_pass else "fail",
                "L2_sanity": "pass" if l2_pass else "fail",
                "L3_grounding": "pass" if l3_pass else "fail",
                "L4_chart": "pass" if l4_pass else "fail",
                "L5_rubric": "pass" if l5_pass else "fail",
            },
            "scores": {
                "recompute": l1_score,
                "sanity": l2_score,
                "grounding": l3_score,
                "rubric": l5_score,
            },
            "issues": issues,
        }

    def _verify_l1_recompute(self, answer: Dict[str, Any], dataset_id: str) -> Tuple[bool, float, List[Dict[str, Any]]]:
        """Independent query path to reproduce headline numbers."""
        claimed_numbers = answer.get("numbers", {})
        issues = []
        if not claimed_numbers:
            return True, 1.0, []

        matches = 0
        total_checks = 0

        for metric_name, val in claimed_numbers.items():
            total_checks += 1
            alt_val = self._independent_recompute(metric_name, dataset_id)
            if alt_val is None:
                matches += 1  # Cannot independently check this metric, skip penalty
                continue

            delta = abs(float(val) - float(alt_val))
            denom = abs(float(alt_val)) if alt_val != 0 else 1.0
            delta_pct = (delta / denom) * 100.0

            if delta_pct <= (self.tolerance * 100.0):
                matches += 1
            else:
                issues.append({
                    "layer": "L1",
                    "metric": metric_name,
                    "analyst": float(val),
                    "critic": float(alt_val),
                    "delta_pct": round(delta_pct, 2),
                    "hint": f"Number differs by {delta_pct:.2f}% (tolerance is {self.tolerance*100:.1f}%)"
                })

        score = matches / total_checks if total_checks else 1.0
        return len(issues) == 0, score, issues

    def _independent_recompute(self, metric_name: str, dataset_id: str) -> Optional[float]:
        """Alternative formulation using different grouping/filtering."""
        try:
            if metric_name in ["gross_revenue", "revenue"]:
                # Alternative formulation: aggregate through individual orders
                res = self.con.execute(f"""
                    WITH ord AS (
                        SELECT order_id, SUM(unit_price * quantity) as o_rev
                        FROM fact_order_lines
                        WHERE dataset_id = '{dataset_id}' AND row_class = 'sale'
                        GROUP BY 1
                    )
                    SELECT SUM(o_rev) FROM ord;
                """).fetchone()[0]
                return float(res) if res is not None else None

            elif metric_name == "net_revenue":
                res = self.con.execute(f"""
                    SELECT SUM(line_total) FROM fact_order_lines 
                    WHERE dataset_id = '{dataset_id}' AND row_class IN ('sale', 'cancellation');
                """).fetchone()[0]
                return float(res) if res is not None else None

            elif metric_name == "orders":
                # Alternative formulation: count order IDs grouped by customer
                res = self.con.execute(f"""
                    WITH cust_orders AS (
                        SELECT customer_token, COUNT(DISTINCT order_id) as c_cnt
                        FROM fact_order_lines 
                        WHERE dataset_id = '{dataset_id}' AND row_class = 'sale'
                        GROUP BY 1
                    )
                    SELECT SUM(c_cnt) FROM cust_orders;
                """).fetchone()[0]
                return float(res) if res is not None else None

            elif metric_name == "customers":
                res = self.con.execute(f"""
                    SELECT COUNT(DISTINCT customer_token) 
                    FROM fact_order_lines 
                    WHERE dataset_id = '{dataset_id}' AND row_class = 'sale' AND customer_token IS NOT NULL;
                """).fetchone()[0]
                return float(res) if res is not None else None

            elif metric_name == "repeat_rate":
                res = self.con.execute(f"""
                    WITH c AS (
                        SELECT customer_token, COUNT(DISTINCT order_id) as o 
                        FROM fact_order_lines 
                        WHERE dataset_id = '{dataset_id}' AND row_class = 'sale' AND customer_token IS NOT NULL 
                        GROUP BY 1
                    )
                    SELECT AVG((o >= 2)::INT) FROM c;
                """).fetchone()[0]
                return float(res) if res is not None else None
        except Exception:
            return None

        return None

    def _verify_l2_sanity(self, answer: Dict[str, Any]) -> Tuple[bool, float, List[Dict[str, Any]]]:
        """Check invariants: bounds, percentages, non-negative counts."""
        issues = []
        claimed = answer.get("numbers", {})

        for k, v in claimed.items():
            if "rate" in k or "share" in k or "pct" in k:
                if v < 0 or v > 100.0:
                    issues.append({"layer": "L2", "metric": k, "error": f"Percentage out of bounds [0, 100]: {v}"})
            if "orders" in k or "units" in k or "customers" in k:
                if v < 0:
                    issues.append({"layer": "L2", "metric": k, "error": f"Count cannot be negative: {v}"})

        passed = len(issues) == 0
        return passed, 1.0 if passed else 0.0, issues

    def _verify_l3_grounding(self, answer: Dict[str, Any]) -> Tuple[bool, float, List[Dict[str, Any]]]:
        """Verify each numerical figure mentioned in headline/explanation exists in evidence."""
        headline = answer.get("headline", "")
        explanation = answer.get("explanation", "")
        full_text = f"{headline} {explanation}"

        # Extract numerical tokens (e.g. £62.77M, 19,790, 4.2%)
        text_numbers = re.findall(r"\b\d+(?:,\d+)*(?:\.\d+)?\b", full_text)
        evidence_data = answer.get("evidence", {})
        issues = []

        if not text_numbers:
            return True, 1.0, []

        # Flatten evidence values
        flat_evidence_strs = []
        if isinstance(evidence_data, dict):
            for v in evidence_data.values():
                if isinstance(v, (int, float)):
                    flat_evidence_strs.append(str(round(v, 2)))
                    flat_evidence_strs.append(f"{v:,.0f}")
                    flat_evidence_strs.append(f"{v:,.2f}")
                elif isinstance(v, list):
                    for item in v:
                        flat_evidence_strs.append(str(item))

        grounded_count = 0
        for num_str in text_numbers:
            clean_num = num_str.replace(",", "")
            # Allow common narrative integers like 1, 2, 10, 30, 2019
            if clean_num in ["1", "2", "3", "4", "5", "10", "30", "90", "2018", "2019", "2020"]:
                grounded_count += 1
                continue
            if any(clean_num in str(ev) for ev in flat_evidence_strs) or any(num_str in str(ev) for ev in flat_evidence_strs):
                grounded_count += 1
            else:
                issues.append({"layer": "L3", "error": f"Claimed number '{num_str}' is ungrounded in queried evidence."})

        score = round(grounded_count / max(1, len(text_numbers)), 2)
        passed = len(issues) == 0
        return passed, score, issues

    def _verify_l4_chart(self, answer: Dict[str, Any]) -> Tuple[bool, float, List[Dict[str, Any]]]:
        """Verify chart spec matches claimed dimensions and units."""
        chart = answer.get("chart")
        if not chart:
            return True, 1.0, []

        issues = []
        if not chart.get("type"):
            issues.append({"layer": "L4", "error": "Chart missing type specification"})
        if not chart.get("x") or not chart.get("y"):
            issues.append({"layer": "L4", "error": "Chart missing x or y axis mappings"})

        passed = len(issues) == 0
        return passed, 1.0 if passed else 0.5, issues

    def _verify_l5_rubric(self, question: str, answer: Dict[str, Any]) -> Tuple[bool, float, List[Dict[str, Any]]]:
        """Rubric check for causal overreach, ungrounded claims, and missing currency labels."""
        text = f"{answer.get('headline', '')} {answer.get('explanation', '')}".lower()
        issues = []
        score = 1.0

        # Causal claim flags on observational data
        causal_words = ["caused by", "proves that", "proves causation", "caused all", "definitely led to", "definitely caused", "guarantees", "will increase revenue by exactly"]
        for cw in causal_words:
            if cw in text:
                issues.append({"layer": "L5", "error": f"Causal overreach detected: '{cw}'. Use associative terms like 'associated with' or 'indicates'."})
                score -= 0.5

        # Currency label check
        assumptions = answer.get("assumptions", [])
        if "currency=GBP" not in assumptions and "GBP" not in text and "£" not in text:
            issues.append({"layer": "L5", "warning": "Currency assumption not explicitly stated."})
            score -= 0.1

        passed = not any("error" in i for i in issues)
        return passed, max(0.0, score), issues
